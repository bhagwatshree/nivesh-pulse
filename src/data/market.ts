const makeCandles = (
  base: number,
  moves: number[],
  start = 1_250_000,
): Candle[] => {
  let previous = base
  return moves.map((move, index) => {
    const open = previous
    const close = +(open + move).toFixed(2)
    const spread = Math.max(Math.abs(move) * 0.55, base * 0.0018)
    const high = +(Math.max(open, close) + spread).toFixed(2)
    const low = +(Math.min(open, close) - spread * 0.75).toFixed(2)
    previous = close
    return {
      time: `${String(9 + Math.floor((15 + index * 5) / 60)).padStart(2, '0')}:${String(
        (15 + index * 5) % 60,
      ).padStart(2, '0')}`,
      open,
      high,
      low,
      close,
      volume: start + index * 81_000 + (index % 3) * 145_000,
    }
  })
}

